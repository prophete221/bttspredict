#!/usr/bin/env node
/**
 * Generate the single build-time date/year source used by bookmaker promo pages.
 * It updates only src/lib/promo-build-date.generated.ts; offer text, codes,
 * publication dates, URLs and the five protected SEO pages are not rewritten.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const DEFAULT_OUTPUT = path.join(ROOT, 'src/lib/promo-build-date.generated.ts')

function dakarDate(now = new Date()) {
  const parts = Object.fromEntries(new Intl.DateTimeFormat('en-CA', {
    timeZone: 'Africa/Dakar', year: 'numeric', month: '2-digit', day: '2-digit',
  }).formatToParts(now).map(({ type, value }) => [type, value]))
  return `${parts.year}-${parts.month}-${parts.day}`
}

function parseArgs(argv) {
  const options = {}
  for (const arg of argv) {
    if (arg.startsWith('--date=')) options.date = arg.slice('--date='.length)
    else if (arg.startsWith('--output=')) options.output = arg.slice('--output='.length)
    else throw new Error(`Argument inattendu : ${arg}`)
  }
  return options
}

function validateDate(value) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(value)) throw new Error('La date doit être au format YYYY-MM-DD')
  const parsed = new Date(`${value}T00:00:00.000Z`)
  if (Number.isNaN(parsed.getTime()) || parsed.toISOString().slice(0, 10) !== value) {
    throw new Error(`Date civile invalide : ${value}`)
  }
  return value
}

function main() {
  const options = parseArgs(process.argv.slice(2))
  const reviewDate = validateDate(options.date || dakarDate())
  const currentYear = Number(reviewDate.slice(0, 4))
  const outputPath = options.output ? path.resolve(options.output) : DEFAULT_OUTPUT
  const content = [
    '// Generated by scripts/update-promo-dates.mjs before each static build.',
    '// This is a build date for promo metadata, not a claim that an operator offer was verified.',
    `export const PROMO_REVIEW_DATE = '${reviewDate}'`,
    `export const PROMO_CURRENT_YEAR = ${currentYear}`,
    '',
  ].join('\n')

  fs.mkdirSync(path.dirname(outputPath), { recursive: true })
  if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, 'utf8') !== content) {
    fs.writeFileSync(outputPath, content, 'utf8')
  }
  console.log(`[promo-date] date Dakar=${reviewDate}; année=${currentYear}; module généré.`)
}

try {
  main()
} catch (error) {
  console.error(`[promo-date] Refus : ${error instanceof Error ? error.message : String(error)}`)
  process.exitCode = 1
}
