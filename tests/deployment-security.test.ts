import fs from 'node:fs'
import { describe, expect, it } from 'vitest'

const workflow = fs.readFileSync('.github/workflows/deploy.yml', 'utf8')
const deploy = workflow.split('\n  deploy:')[1] ?? ''
const preflight = fs.readFileSync('scripts/ftp-safe-preflight.lftp', 'utf8')
const planner = fs.readFileSync('scripts/prepare-stale-match-deletions.mjs', 'utf8')
const sitemapFilter = fs.readFileSync('scripts/filter-sitemap-match-urls.mjs', 'utf8')
const statePlanner = fs.readFileSync('scripts/prepare-ftp-deploy-plan.mjs', 'utf8')
const ftpDiff = fs.readFileSync('scripts/ftp-diff.mjs', 'utf8')
const ftpUploadPlan = fs.readFileSync('scripts/prepare-ftp-upload-allowlist.mjs', 'utf8')

describe('deployment safety gates', () => {
  it('allows the production API only on VIP documents and admin, preserving the other pages CSP', () => {
    const htaccess = fs.readFileSync('public/.htaccess', 'utf8')
    const match = htaccess.match(/^SetEnvIf Request_URI "([^"]+)" vip_api_csp$/m)
    expect(match).not.toBeNull()
    const scope = new RegExp(match?.[1] ?? '(?!)')
    for (const route of ['/vip', '/vip/', '/vip.html', '/en/vip', '/en/vip/', '/en/vip.html', '/ar/vip', '/ar/vip/', '/ar/vip.html', '/vip-admin/admin.html']) {
      expect(scope.test(route), route).toBe(true)
    }
    for (const route of ['/', '/pronostics', '/en', '/vip-offer', '/vip/extra', '/match/vip', '/vip-admin/admin.js', '/ar/vip-admin/admin.html']) {
      expect(scope.test(route), route).toBe(false)
    }
    const headers = htaccess.split('\n').filter(line => line.startsWith('Header always set Content-Security-Policy '))
    const base = headers.find(line => line.endsWith('env=!vip_api_csp'))
    const vip = headers.find(line => line.endsWith('env=vip_api_csp'))
    const origin = 'https://bttspredict-vip-production-api.luxxdii.workers.dev'
    expect(headers).toHaveLength(2)
    expect(base).not.toContain(origin)
    expect(vip).toContain(origin)
    expect(vip?.replace(` ${origin}`, '').replace(' env=vip_api_csp', '')).toBe(base?.replace(' env=!vip_api_csp', ''))
  })

  it('runs hard-failing tests, Python, lint, typecheck and build before any FTP operation', () => {
    const firstTransfer = deploy.indexOf('lftp -u')
    const action = deploy.indexOf('name: Deploy to bttspredict.com via FTP (validated allowlist, no delete)')
    const cooldown = deploy.indexOf('sleep 300')
    expect(firstTransfer).toBeGreaterThan(0)
    expect(cooldown).toBeGreaterThan(firstTransfer)
    expect(cooldown).toBeLessThan(action)
    expect(action).toBeGreaterThan(firstTransfer)
    expect(deploy).toContain('Refroidissement 300 s pour la protection anti-flood LWS')
    for (const command of ['run: npm test', 'python3 -m unittest discover', 'run: npm run lint', 'run: npx tsc --noEmit', 'run: npm run build -- --webpack']) {
      expect(deploy.indexOf(command)).toBeGreaterThan(0)
      expect(deploy.indexOf(command)).toBeLessThan(firstTransfer)
      const step = deploy.split(/(?=^      - name: )/m).find((part) => part.includes(command))
      expect(step).not.toContain('continue-on-error: true')
    }
    expect(deploy).toContain("github.ref == 'refs/heads/main'")
    expect(deploy).toContain("github.event_name != 'pull_request'")
    expect(deploy.split("github.event_name == 'push' && !contains(github.event.head_commit.message, '[code-only]')").length - 1).toBe(16)
    expect(deploy).not.toContain("github.event_name == 'schedule' || github.event_name == 'push' ||")
    expect(workflow).toContain("paths-ignore:\n      - 'public/**'")
    expect(workflow).toContain('cancel-in-progress: false')
    const publicEnrichment = deploy.indexOf('run: python scripts/enrich_predictions.py')
    const privateVipAnalysis = deploy.indexOf('run: python scripts/enrich_vip_candidates.py')
    const privateVipFilter = deploy.indexOf('run: node scripts/vip-candidate-source.mjs')
    expect(privateVipAnalysis).toBeGreaterThan(publicEnrichment)
    expect(privateVipAnalysis).toBeLessThan(privateVipFilter)
    const privateVipStep = deploy.split('      - name: Analyze private VIP candidate variants')[1]?.split('      - name: ')[0] ?? ''
    expect(privateVipStep).toContain('GEMINI_API_KEY: ${{ secrets.GEMINI_API_KEY }}')
    expect(privateVipStep).toContain('run: python scripts/enrich_vip_candidates.py')
    expect(privateVipStep).not.toContain('run: python scripts/enrich_predictions.py')
    const commitDataStep = deploy.split('      - name: Commit data')[1]?.split('      - name: ')[0] ?? ''
    expect(commitDataStep).toContain("github.event_name != 'push'")
    expect(commitDataStep).toContain("inputs.mode != 'code'")
  })

  it('uses the historical plain FTP host for preflight and restoration', () => {
    expect(deploy).toContain('lftp -u "$FTP_USERNAME,$FTP_PASSWORD" -e "source scripts/ftp-safe-preflight.lftp" "ftp://${FTP_SERVER}"')
    expect(deploy).toContain('lftp -u "$FTP_USERNAME,$FTP_PASSWORD" -e "set ssl:verify no; set net:timeout 60; set net:max-retries 2; set cmd:fail-exit yes; put out/predeploy-backups/robots.txt -o robots.txt; put out/predeploy-backups/sitemap.xml -o sitemap.xml; bye" "ftp://${FTP_SERVER}"')
    expect(deploy).not.toContain('"ftp://${FTP_SERVER}" -f scripts/ftp-safe-preflight.lftp')
    expect(deploy).not.toContain('"ftp://${FTP_SERVER}" -e')
    expect(preflight).not.toContain('set ftp:ssl-force true')
    expect(preflight).not.toContain('set ftp:ssl-protect-data true')
  })

  it('bounds remote state reads and fails closed before Match listings if both states are absent', () => {
    expect(preflight).toContain('set net:timeout 10')
    expect(preflight).toContain('set net:max-retries 1')
    expect(preflight).toContain('get deploy-manifest.json -o out/deploy-manifest.prev.json')
    expect(preflight).toContain('scripts/validate-ftp-deploy-state.mjs')
    expect(preflight.indexOf('get deploy-manifest.json')).toBeLessThan(preflight.indexOf('find en/match'))
    expect(preflight.indexOf('!node scripts/validate-ftp-deploy-state.mjs')).toBeLessThan(preflight.indexOf('find en/match'))
    expect(statePlanner).toContain('ni .ftp-deploy-sync-state-safe.json ni .ftp-deploy-sync-state.json')
    expect(statePlanner).toContain('avant tout transfert et toute suppression')
  })

  it('uses a full-manifest differential v2 allowlist and never deletes broadly', () => {
    expect(deploy).toContain('"ftp://${FTP_SERVER}"')
    expect(statePlanner).toContain("'scripts/ftp-diff.mjs', 'prepare', '--require-prev', '--allow-legacy-v1'")
    expect(statePlanner).toContain("diffArgs.push('--code-only')")
    expect(statePlanner).toContain('`--diff-stats=${diffStatsPath}`')
    expect(statePlanner).toContain("path.join(outDir, 'match-only-inventory.tsv')")
    expect(statePlanner).not.toContain('--live-inventory')
    expect(statePlanner).toContain('matchOnlyInventoryUsedForDiff: false')
    const diffPlan = statePlanner.indexOf('runNode(diffArgs)')
    const uploadPlan = statePlanner.indexOf('scripts/prepare-ftp-upload-allowlist.mjs')
    const stateSeedWrite = statePlanner.indexOf('fs.writeFileSync(stateSeedPath')
    expect(diffPlan).toBeGreaterThan(0)
    expect(uploadPlan).toBeGreaterThan(diffPlan)
    expect(stateSeedWrite).toBeGreaterThan(uploadPlan)
    expect(preflight.indexOf('source out/stale-match-delete.lftp')).toBeGreaterThan(preflight.indexOf('!node scripts/prepare-ftp-deploy-plan.mjs'))
    expect(ftpDiff).toContain("'predictions.json'")
    expect(ftpDiff).toContain("'predictions-archive/'")
    expect(ftpDiff).toContain("'match-only-inventory.tsv'")
    expect(ftpDiff).toContain('remoteManifestMustNotBePublished: codeOnly')
    expect(deploy).toContain('Manifeste distant laissé intact en mode code-only')
    expect(deploy).toContain('out/deploy-diff-stats.json')
    expect(deploy).toContain('node scripts/prepare-ftp-upload-allowlist.mjs report')
    expect(statePlanner).toContain("'deploy-upload-commands.lftp'")
    expect(deploy).toContain('source out/deploy-upload-commands.lftp')
    expect(deploy).toContain('out/deploy-transfer.log')
    expect(deploy).toContain('out/deploy-transfer-report.json')
    expect(deploy).toContain('Envoi différentiel par commandes put exactes (une par fichier), depuis le manifeste distant complet; aucune suppression générale.')
    expect(deploy).toContain('Transfert FTP par allowlist en échec')
    expect(ftpUploadPlan).toContain('getDifferentialPaths')
    expect(ftpUploadPlan).toContain('diffStats.changedPaths')
    expect(ftpUploadPlan).toContain('transfert intégral refusé')
    expect(ftpUploadPlan).toContain("'deploy-upload-commands.lftp'")
    expect(deploy).not.toContain('mirror --reverse')
    expect(deploy).not.toContain('--include-rx-from')
    expect(deploy).not.toContain('FTP-Deploy-Action')
    expect(deploy).not.toContain('dangerous-clean-slate')
    expect(deploy).not.toContain('remove-existing-files')
    expect(deploy).not.toContain('mirror --delete')
    expect(deploy).not.toContain('--delete')
    expect(deploy).not.toContain('Free server disk')
    expect(deploy).not.toContain('rm -rf')
    expect(deploy).not.toContain('rm -r ')
    expect(ftpUploadPlan).toContain("const CODE_ONLY_DATA_FILES = new Set(")
    expect(ftpUploadPlan).toContain("'predictions-archive/'")
    expect(ftpUploadPlan).toContain("const EXPLICIT_ROOT_UPLOADS = ['robots.txt', 'sitemap.xml']")
    expect(ftpUploadPlan).toContain("const REQUIRED_ROOT_FILES = ['.htaccess', ...EXPLICIT_ROOT_UPLOADS]")
  })

  it('limits remote listing and deletes to verified EN/AR Match pages, never root /match or unrelated files', () => {
    expect(deploy).toContain('scripts/ftp-safe-preflight.lftp')
    const liveFindCommands = preflight.split('\n').map(line => line.trim()).filter(line => line.startsWith('find '))
    expect(liveFindCommands).toEqual([
      'find en/match > /tmp/ftp-en-match-list.txt',
      'find ar/match > /tmp/ftp-ar-match-list.txt',
    ])
    expect(preflight).toContain('source out/stale-match-delete.lftp')
    expect(planner).toContain("matchPath.locale === 'fr'")
    expect(planner).toContain("category: 'match-root-out-of-scope'")
    expect(planner).toContain("status === 'finished'")
    const currentManifestGuard = planner.indexOf('if (currentFiles.has(remotePath))')
    const deletionCandidate = planner.indexOf('deletions.push({ path: remotePath')
    expect(currentManifestGuard).toBeGreaterThan(0)
    expect(currentManifestGuard).toBeLessThan(deletionCandidate)
    expect(planner).not.toContain('assertNoFinishedMatchFiles')
    expect(planner).toContain("category: 'non-match-unverified'")
    expect(planner).not.toContain('ftp.delete(')
    expect(sitemapFilter).toContain('/^(?:en|ar)\\/match\\/')
    expect(sitemapFilter).not.toContain('(?:(?:en|ar)\\/)?match')
    expect(preflight).not.toContain('get .htaccess')
    expect(preflight).toContain('get robots.txt -o out/predeploy-backups/robots.txt')
    expect(preflight).toContain('get sitemap.xml -o out/predeploy-backups/sitemap.xml')
  })

  it('keeps deployment evidence out of the allowlist and preserves protected root state', () => {
    expect(deploy).toContain('node scripts/ftp-diff.mjs manifest')
    expect(deploy).toContain('out/match-only-inventory.tsv')
    expect(deploy).not.toContain('out/remote-inventory.tsv')
    expect(deploy).toContain('ftp-action-state-report.json')
    expect(statePlanner).toContain('buildSafeStateSeed')
    expect(statePlanner).toContain("new Set(['robots.txt', 'sitemap.xml'])")
    expect(statePlanner).toContain('droppedRemoteOnlyRecordCount')
    expect(statePlanner).toContain('aucun fichier distant absent du build ne peut être supprimé')
    expect(statePlanner).toContain("entry.type === 'file' && forced.has(name)")
    expect(ftpDiff).toContain("'ftp-action-state-report.json'")
    expect(ftpDiff).toContain("'deploy-upload-commands.lftp'")
    expect(ftpDiff).toContain("'deploy-transfer-report.json'")
    expect(deploy).toContain('deploy-manifest.json')
    expect(ftpDiff).toContain('deploy-diff-stats.json')
  })

  it('filters sitemap entries only for exact EN/AR deletions and preserves root files around the upload', () => {
    expect(preflight).toContain('node scripts/prepare-ftp-deploy-plan.mjs')
    expect(statePlanner).toContain('scripts/prepare-stale-match-deletions.mjs')
    expect(statePlanner).toContain('scripts/filter-sitemap-match-urls.mjs')
    expect(statePlanner).toContain("/^(?:en|ar)\\/match\\//.test(item.path)")
    expect(statePlanner).toContain('`--previous=${previousSitemapPath}`')
    expect(statePlanner).toContain('`--output=${path.join(outDir, \'sitemap.xml\')}`')
    expect(statePlanner).toContain('`--report=${path.join(outDir, \'sitemap-match-filter.json\')}`')
    expect(deploy).toContain('Restore protected root files if FTP transfer did not complete')
    expect(deploy).toContain('steps.ftp-upload.outcome != \'success\'')
    expect(deploy).toContain('put out/predeploy-backups/robots.txt -o robots.txt')
    expect(deploy).toContain('put out/predeploy-backups/sitemap.xml -o sitemap.xml')
    expect(deploy).toContain('set ssl:verify no; set net:timeout 60; set net:max-retries 2; set cmd:fail-exit yes; put out/predeploy-backups/robots.txt')
    expect(deploy).toContain('Deploy .htaccess with historical temporary rename')
    expect(deploy).toContain('rm -f ./.htaccess.deploy; put out/.htaccess -o ./.htaccess.deploy; rm -f ./.htaccess; mv ./.htaccess.deploy ./.htaccess')
    expect(deploy).toContain('⚠️ rm+rename refusé — tentative STOR direct')
    expect(ftpUploadPlan).toContain("const REQUIRED_ROOT_FILES = ['.htaccess', ...EXPLICIT_ROOT_UPLOADS]")
    expect(deploy).toContain('out/stale-match-pages.json')
    expect(deploy).toContain('out/orphan-review.json')
    expect(deploy).toContain('out/sitemap-match-filter.json')
  })

  it('keeps the html lang fix after build and before the local manifest', () => {
    expect(deploy).toContain('node scripts/fix-html-lang.mjs out')
    const build = deploy.indexOf('run: npm run build')
    const copy = deploy.indexOf('Copy routing files')
    const langFix = deploy.indexOf('node scripts/fix-html-lang.mjs out')
    const manifest = deploy.indexOf('node scripts/ftp-diff.mjs manifest')
    expect(build).toBeGreaterThan(0)
    expect(langFix).toBeGreaterThan(copy)
    expect(langFix).toBeLessThan(manifest)
  })

  it('requires a code-only targeted history deploy and validates its exact payload before FTP', () => {
    expect(deploy).toContain("contains(github.event.head_commit.message, '[history-json]') && !contains(github.event.head_commit.message, '[code-only]')")
    expect(deploy).toContain('Validate targeted history payload')
    expect(deploy).toContain('history.stats?.[name] !== value')
    expect(deploy).toContain('may5Keys.length !== 12')
    expect(deploy).toContain("key.startsWith('2026-11-07|')")
    expect(deploy).toContain('nov7Lost.length !== 0')
    expect(deploy).toContain('nov7Keys.length !== 15')
    expect(deploy).toContain('total: 525, won: 424, lost: 101, unverifiable: 203, pending: 27, archivedTotal: 755')
    expect(deploy).toContain('Verify targeted history files in static export')
    expect(deploy).toContain('cmp public/win-history.json out/win-history.json')
    expect(deploy).toContain('cmp public/history-exclusions.json out/history-exclusions.json')
    expect(statePlanner).toContain("diffArgs.push('--history-json-only', '--force-path=win-history.json', '--force-path=history-exclusions.json')")
    expect(ftpDiff).toContain('HISTORY_JSON_ONLY_FILES')
    expect(ftpUploadPlan).toContain('assertHistoryJsonOnlyPlan')
    expect(deploy).toContain('assertHistoryJsonOnlyPlan(plan, stats)')
    expect(deploy).toContain('commandFile !== `${plan.commands.join(\'\\n\')}\\n`')
    const markerGate = deploy.indexOf('Require code-only marker for targeted history deploy')
    const prune = deploy.indexOf('Prune old predictions archives')
    const allowlist = deploy.indexOf('Prepare validated upload allowlist')
    const ftp = deploy.indexOf('name: Deploy to bttspredict.com via FTP (validated allowlist, no delete)')
    expect(markerGate).toBeGreaterThan(0)
    expect(markerGate).toBeLessThan(prune)
    expect(allowlist).toBeGreaterThan(0)
    expect(allowlist).toBeLessThan(ftp)
  })

  it('keeps manual VIP generation private and separate from public deployment', () => {
    const vipJob = workflow.split('\n  vip-candidates-only:')[1]?.split('\n  deploy:')[0] ?? ''
    expect(workflow).toContain('          - vip')
    expect(workflow).toContain("group: ${{ github.event_name == 'workflow_dispatch' && inputs.mode == 'vip' && 'vip-candidates-only' || format('deploy-{0}', github.ref) }}")
    expect(workflow).toContain("inputs.mode != 'vip'")
    expect(workflow).toContain("!contains(github.event.head_commit.message, '[skip ci]')")
    expect(vipJob).toContain("github.event_name == 'workflow_dispatch' && inputs.mode == 'vip'")
    expect(vipJob).toContain('github.actor == github.repository_owner')
    expect(vipJob).toContain('id-token: write')
    expect(vipJob).toContain('GEMINI_API_KEY: ${{ secrets.GEMINI_API_KEY }}')
    expect(vipJob.match(/VIP_CANDIDATE_API_URL: https:\/\/bttspredict-vip-production-api\.luxxdii\.workers\.dev/g)).toHaveLength(2)
    expect(vipJob).not.toContain('vars.VIP_CANDIDATE_API_URL')
    expect(workflow.match(/VIP_CANDIDATE_API_URL: https:\/\/bttspredict-vip-production-api\.luxxdii\.workers\.dev/g)).toHaveLength(3)
    expect(workflow).not.toContain('vars.VIP_CANDIDATE_API_URL')
    for (const step of [
      'python scripts/enrich_vip_candidates.py',
      'node scripts/vip-candidate-source.mjs .private/vip-gemini-candidates.json public/predictions.json .private/vip-candidates.json',
      'node scripts/sync-vip-candidates.mjs .private/vip-candidates.json',
      "python3 -m unittest discover -s tests -p 'enrich_vip_candidates_test.py' -v",
    ]) expect(vipJob).toContain(step)
    for (const forbidden of [
      'lftp', 'FTP_SERVER', 'quick-update-predictions.mjs', 'finalize-predictions.mjs',
      'update-win-history.mjs', 'submit-indexnow.mjs', 'telegram', 'git push', 'npm run build',
    ]) expect(vipJob).not.toContain(forbidden)
  })

  it('keeps the FTP diagnostic workflow read-only and the inventory utility write-free', () => {
    const diagnostic = fs.readFileSync('.github/workflows/ftp-diagnostic.yml', 'utf8')
    expect(diagnostic).toContain('contents: read')
    expect(diagnostic).not.toMatch(/lftp|mirror --|git push|secrets\.GEMINI/)
    expect(diagnostic).toContain('python3 scripts/ftp-inventory.py')
    expect(diagnostic).toContain('if: always()')

    const source = fs.readFileSync('scripts/ftp-inventory.py', 'utf8')
    for (const forbidden of ['storbinary(', 'storlines(', '.mkd(', '.delete(', '.rmd(', '.rename(', '.sendcmd(', '.voidcmd("']) {
      expect(source).not.toContain(forbidden)
    }
    expect(source).toContain('FORBIDDEN_COMMANDS')
    expect(source).toContain('READABLE_ROOT_FILES')
    expect(source).toContain('ROOT_BACKUP_FILES')
    expect(source).toContain('prot_p')
    expect(source).toContain('ftp.auth()')
  })
})
